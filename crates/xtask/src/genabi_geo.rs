//! The geodesy and tile vectors of `cargo xtask gen-abi` (ADR-51 GE9): `tests/vectors/tiles.json`
//! and `tests/vectors/geodesy.json`, produced by the `geo` crate and checked by `geo-stream`'s
//! Vitest suite, so Rust and TypeScript are held to the same numbers.

use geo::angles::RAD;
use geo::testkit::Rng;
use geo::tile::{MAX_LEVEL, TileId, tile_for};
use geo::{Geodetic, Wgs84Frame, geodetic_to_ecef};
use serde_json::{Value, json};

use crate::genabi::lines;

fn tile_json(t: TileId) -> Value {
    let b = t.bounds();
    let (lat0, lon0) = t.post_latlon(0, 0);
    let (lat1, lon1) = t.post_latlon(128, 64);
    json!({
        "z": t.z,
        "x": t.x,
        "y": t.y,
        "id": t.id(),
        "bounds": [b.lat_north, b.lat_south, b.lon_west, b.lon_east],
        "parent": t.parent().map(TileId::id),
        "children": if t.z < MAX_LEVEL { json!(t.children().map(TileId::id)) } else { Value::Null },
        "cell": t.cell().map(|(x, y)| [x, y]),
        "post_0_0": [lat0, lon0],
        "post_128_64": [lat1, lon1],
    })
}

fn point_json(lat: f64, lon: f64, z: u8) -> Value {
    let t = tile_for(lat, lon, z);
    json!({ "lat": lat, "lon": lon, "z": z, "x": t.x, "y": t.y, "id": t.id() })
}

/// 64 cases: the plan's vectors, two seeded tiles per level, and points at the antimeridian, the
/// poles and at random.
pub fn tiles_vectors() -> String {
    let named = |z, x, y| TileId::new(z, x, y).expect("a valid tile");
    let mut tiles = vec![named(5, 33, 7)];
    tiles.extend(named(5, 33, 7).children());
    tiles.push(named(12, 4_321, 1_234));
    tiles.push(named(13, 16_383, 8_191));
    let mut rng = Rng::new(100);
    for z in 0..=MAX_LEVEL {
        for _ in 0..2 {
            let x = (rng.next_u64() % (2u64 << z)) as u32;
            let y = (rng.next_u64() % (1u64 << z)) as u32;
            tiles.push(named(z, x, y));
        }
    }
    let pi = core::f64::consts::PI;
    let mut points = Vec::new();
    for (lat, lon, z) in [
        (0.3, pi, 5),
        (0.3, -pi, 5),
        (53.4 * RAD, pi, 10),
        (53.4 * RAD, -pi, 10),
        (53.4 * RAD, pi - 1e-9, 12),
        (-0.7, -pi + 1e-9, 12),
        (pi / 2.0, 0.0, 3),
        (pi / 2.0, 2.0, 13),
        (-pi / 2.0, 0.0, 3),
        (-pi / 2.0, -2.0, 13),
        (46.55 * RAD, 8.0 * RAD, 5),
        (46.55 * RAD, 8.0 * RAD, 12),
    ] {
        points.push(point_json(lat, lon, z));
    }
    while tiles.len() + points.len() < 64 {
        let lat = rng.uniform(-pi / 2.0, pi / 2.0);
        let lon = rng.lon();
        let z = (rng.next_u64() % u64::from(MAX_LEVEL + 1)) as u8;
        points.push(point_json(lat, lon, z));
    }
    let tiles: Vec<Value> = tiles.into_iter().map(tile_json).collect();
    format!(
        "{{\n  \"note\": \"Generated by `cargo xtask gen-abi` from the geo crate's tile maths. Do not edit.\",\n  \"tiles\": {},\n  \"points\": {}\n}}\n",
        lines(&tiles),
        lines(&points)
    )
}

/// 100 geodetic → ECEF → BF cases in the frame anchored at 46.55° N, 8.0° E.
pub fn geodesy_vectors() -> String {
    let f = Wgs84Frame::new(46.55 * RAD, 8.0 * RAD);
    let mut rng = Rng::new(101);
    let cases: Vec<Value> = (0..100)
        .map(|_| {
            let g = Geodetic::new(
                rng.uniform(38.0, 55.0) * RAD,
                rng.uniform(-4.0, 20.0) * RAD,
                rng.uniform(-500.0, 30_000.0),
            );
            let q = geodetic_to_ecef(g);
            let p = f.ecef_to_bf(q);
            json!({ "geo": [g.lat_rad, g.lon_rad, g.h_m], "ecef": [q.x, q.y, q.z], "bf": [p.x, p.y, p.z] })
        })
        .collect();
    let rows: Vec<[f64; 3]> = (0..3).map(|i| f.rot.row(i).to_array()).collect();
    format!(
        "{{\n  \"note\": \"Generated by `cargo xtask gen-abi` from geo::Wgs84Frame. Do not edit.\",\n  \"tolerance_m\": 1e-6,\n  \"anchor\": {},\n  \"a_ecef\": {},\n  \"rot\": {},\n  \"cases\": {}\n}}\n",
        json!([f.anchor.lat_rad, f.anchor.lon_rad]),
        json!(f.a_ecef.to_array()),
        json!(rows),
        lines(&cases)
    )
}

/// The three tiles of the format vector (GP5): relief, a flat tile (`h_min = h_max`), and a coast
/// with mixed landcover.
fn gpk_tiles() -> Vec<geo_pack::DecodedTile> {
    use geo::codec::{bounds_f32, quantise};
    use geo::tile::{LC_COUNT, POST_COUNT, POSTS};
    use geo_pack::tile::{zero_landcover, zero_posts};
    let relief =
        |r: usize, c: usize| 400.0 + 3.5 * r as f64 + 0.25 * (c * c) as f64 - 0.01 * (r * c) as f64;
    let mk = |id: TileId,
              f: &dyn Fn(usize, usize) -> f64,
              lc: &dyn Fn(usize) -> u8,
              eps: f32,
              quality: u8| {
        let hs: Vec<f64> = (0..POST_COUNT).map(|k| f(k / POSTS, k % POSTS)).collect();
        let (lo, hi) = hs
            .iter()
            .fold((f64::INFINITY, f64::NEG_INFINITY), |(a, b), &h| {
                (a.min(h), b.max(h))
            });
        let (h_min, h_max) = bounds_f32(lo, hi);
        let mut posts = zero_posts();
        for (p, &h) in posts.iter_mut().zip(&hs) {
            *p = quantise(h, h_min, h_max);
        }
        let mut landcover = zero_landcover();
        for (k, v) in landcover.iter_mut().enumerate().take(LC_COUNT) {
            *v = lc(k);
        }
        geo_pack::DecodedTile {
            id,
            h_min,
            h_max,
            eps,
            quality,
            posts,
            landcover,
        }
    };
    let t = |z, x, y| TileId::new(z, x, y).expect("a tile");
    vec![
        mk(t(7, 133, 29), &relief, &|_| 255, 12.5, 1),
        mk(t(8, 266, 58), &|_, _| 553.5, &|_| 255, 0.0, 1),
        mk(
            t(12, 4_256, 928),
            &|r, c| {
                if c < 40 {
                    0.0
                } else {
                    2.0 + 0.5 * (r + c) as f64
                }
            },
            &|k| if k % 64 < 20 { 0 } else { 255 },
            0.0,
            0,
        ),
    ]
}

/// The format vector archive (`tests/vectors/gpk_fixture.gpk`).
pub fn gpk_fixture() -> Vec<u8> {
    let mut w = geo_pack::ArchiveWriter::new(6, 12);
    for tile in gpk_tiles() {
        w.add_tile(&tile);
    }
    let header = geo_pack::HeaderJson {
        datapack: "geo-vectors".into(),
        cell: Some((33, 7)),
        min_level: 6,
        max_level: 12,
        licences: vec!["synthetic".into()],
        sources: vec![],
    };
    w.finish(&header).expect("three distinct tiles")
}

/// What `gpk_fixture.gpk` decodes to (`tests/vectors/gpk.json`).
pub fn gpk_vectors(archive: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let a = geo_pack::Archive::open(archive.to_vec()).expect("the vector archive opens");
    let h = a.header();
    let entries: Vec<Value> = a
        .entries()
        .iter()
        .map(|e| {
            let id = TileId::from_id(e.tile_id).expect("an id");
            let t = a.tile(id).expect("decodes").expect("stored");
            let le: Vec<u8> = t.posts.iter().flat_map(|p| p.to_le_bytes()).collect();
            let samples: Vec<u16> = [0usize, 1, 128, 129, 8_320, 16_640]
                .iter()
                .map(|&k| t.posts[k])
                .collect();
            json!({
                "tile_id": e.tile_id, "z": id.z, "x": id.x, "y": id.y,
                "h_min": t.h_min, "h_max": t.h_max, "eps": t.eps, "quality": t.quality,
                "height": [e.layers[0].offset, e.layers[0].length],
                "landcover": [e.layers[1].offset, e.layers[1].length],
                "posts_sha256": crate::util::hex(&Sha256::digest(&le)),
                "landcover_sha256": crate::util::hex(&Sha256::digest(&t.landcover[..])),
                "post_samples": samples,
                "landcover_ocean": t.landcover.iter().map(|&c| usize::from(c == 0)).sum::<usize>(),
                "height_at_8320_m": t.height(8_320),
            })
        })
        .collect();
    format!(
        "{{\n  \"note\": \"Generated by `cargo xtask gen-abi` from geo-pack (GP5). Do not edit.\",\n  \"file\": \"gpk_fixture.gpk\",\n  \"size_bytes\": {},\n  \"header\": {},\n  \"header_json\": {},\n  \"entries\": {}\n}}\n",
        archive.len(),
        json!({
            "header_json_offset": h.header_json_offset, "header_json_len": h.header_json_len,
            "dir_offset": h.dir_offset, "dir_blob_len": h.dir_blob_len, "dir_entry_count": h.dir_entry_count,
            "data_offset": h.data_offset, "data_len": h.data_len, "min_level": h.min_level, "max_level": h.max_level,
        }),
        serde_json::to_string(&a.header_json().to_text()).expect("a string"),
        lines(&entries)
    )
}
